create extension if not exists pgcrypto;

-- ============ KİRACILIK (şirketler ve üyelikler) ============

create table public.orgs (
  id uuid primary key default gen_random_uuid(),
  ad text not null,
  created_at timestamptz not null default now()
);

create table public.org_members (
  org_id uuid not null references public.orgs(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  rol text not null check (rol in ('owner', 'member')),
  email text not null,
  created_at timestamptz not null default now(),
  primary key (org_id, user_id),
  unique (user_id) -- bir kullanıcı yalnız bir şirkete üye olabilir
);

-- Platform davet kodları: yeni şirket ancak bu kodlardan biriyle kurulabilir.
create table public.invite_codes (
  code text primary key,
  note text not null default '',
  created_at timestamptz not null default now(),
  used_by uuid references auth.users(id),
  used_at timestamptz,
  org_id uuid references public.orgs(id)
);

-- Şirket katılım kodları: sahip üretir, mesai arkadaşı bu kodla aynı şirkete katılır.
create table public.org_join_codes (
  code text primary key,
  org_id uuid not null references public.orgs(id) on delete cascade,
  created_by uuid not null,
  created_at timestamptz not null default now(),
  used_by uuid references auth.users(id),
  used_at timestamptz
);

-- ============ YARDIMCI FONKSİYONLAR ============

create or replace function public.current_org_id()
returns uuid language sql stable security definer set search_path = public as $$
  select org_id from org_members where user_id = auth.uid() limit 1
$$;

create or replace function public.is_platform_admin()
returns boolean language sql stable as $$
  select coalesce(lower(auth.jwt()->>'email') = 'timurhan.duzgun.20@hotmail.com', false)
$$;

create or replace function public.rastgele_kod()
returns text language sql volatile as $$
  select upper(encode(gen_random_bytes(4), 'hex'))
$$;

