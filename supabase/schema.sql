-- ============ RPC FONKSİYONLARI ============

-- Yeni şirket kur: davet kodunu doğrula + yak, org + owner üyeliği oluştur.
create or replace function public.kurulus_olustur(davet_kodu text, sirket_adi text)
returns uuid language plpgsql security definer set search_path = public as $$
declare
  v_org uuid;
  v_code text;
begin
  if auth.uid() is null then raise exception 'GIRIS_GEREKLI'; end if;
  if exists (select 1 from org_members where user_id = auth.uid()) then
    raise exception 'ZATEN_UYE';
  end if;
  if coalesce(trim(sirket_adi), '') = '' then raise exception 'SIRKET_ADI_BOS'; end if;

  update invite_codes set used_by = auth.uid(), used_at = now()
    where code = upper(trim(davet_kodu)) and used_by is null
    returning code into v_code;
  if v_code is null then raise exception 'KOD_GECERSIZ'; end if;

  insert into orgs (ad) values (trim(sirket_adi)) returning id into v_org;
  update invite_codes set org_id = v_org where code = v_code;
  insert into org_members (org_id, user_id, rol, email)
    values (v_org, auth.uid(), 'owner', coalesce(auth.jwt()->>'email', ''));
  return v_org;
end $$;

-- Katılım koduyla mevcut şirkete üye ol.
create or replace function public.kurulusa_katil(katilim_kodu text)
returns uuid language plpgsql security definer set search_path = public as $$
declare
  v_org uuid;
begin
  if auth.uid() is null then raise exception 'GIRIS_GEREKLI'; end if;
  if exists (select 1 from org_members where user_id = auth.uid()) then
    raise exception 'ZATEN_UYE';
  end if;
  update org_join_codes set used_by = auth.uid(), used_at = now()
    where code = upper(trim(katilim_kodu)) and used_by is null
    returning org_id into v_org;
  if v_org is null then raise exception 'KOD_GECERSIZ'; end if;
  insert into org_members (org_id, user_id, rol, email)
    values (v_org, auth.uid(), 'member', coalesce(auth.jwt()->>'email', ''));
  return v_org;
end $$;

-- Şirket sahibi, mesai arkadaşı için tek kullanımlık katılım kodu üretir.
create or replace function public.katilim_kodu_olustur()
returns text language plpgsql security definer set search_path = public as $$
declare
  v_kod text;
begin
  if not exists (select 1 from org_members where user_id = auth.uid() and rol = 'owner') then
    raise exception 'SADECE_SAHIP';
  end if;
  v_kod := public.rastgele_kod();
  insert into org_join_codes (code, org_id, created_by)
    values (v_kod, public.current_org_id(), auth.uid());
  return v_kod;
end $$;

-- Platform yöneticisi (satış için) toplu davet kodu üretir.
create or replace function public.davet_kodu_olustur(adet integer, aciklama text default '')
returns setof text language plpgsql security definer set search_path = public as $$
declare
  i int;
  v text;
begin
  if not public.is_platform_admin() then raise exception 'YETKISIZ'; end if;
  for i in 1..least(coalesce(adet, 1), 50) loop
    v := public.rastgele_kod();
    insert into invite_codes (code, note) values (v, coalesce(aciklama, ''));
    return next v;
  end loop;
end $$;

-- Oturum açan kullanıcının üyelik bilgisi (AuthContext bootstrap okuması).
create or replace function public.uyeligim()
returns table (org_id uuid, rol text, org_ad text)
language sql stable security definer set search_path = public as $$
  select m.org_id, m.rol, o.ad
  from org_members m join orgs o on o.id = m.org_id
  where m.user_id = auth.uid()
$$;

